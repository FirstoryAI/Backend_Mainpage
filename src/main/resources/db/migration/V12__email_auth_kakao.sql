-- V12: 휴대폰 문자 인증을 이메일 인증으로 바꾸고 카카오 로그인을 더한다.
-- 휴대폰 번호는 더 받지 않는다 (기존 번호는 개발 데이터뿐이라 지운다). 알림도 문자 대신 이메일.

-- ───────── 회원 ─────────
ALTER TABLE users
    DROP COLUMN phone_enc,
    DROP COLUMN phone_hash,          -- 부분 인덱스 ux_users_phone_hash_active도 함께 지워진다
    DROP COLUMN phone_verified_at,
    ALTER COLUMN password_hash DROP NOT NULL,   -- 카카오로만 가입한 회원은 비밀번호가 없다
    ADD COLUMN email_verified_at timestamptz,   -- 이메일 인증번호 확인 시각, 카카오가 인증한 이메일이면 카카오 가입 시각
    ADD COLUMN kakao_id varchar(40);            -- 카카오 회원번호. 카카오로 가입한 회원만

UPDATE users SET email_verified_at = created_at;   -- 기존 회원(개발 데이터)은 가입 시각으로 채운다
ALTER TABLE users ALTER COLUMN email_verified_at SET NOT NULL;

CREATE UNIQUE INDEX ux_users_kakao_id_active ON users (kakao_id) WHERE deleted_at IS NULL AND kakao_id IS NOT NULL;

-- ───────── 인증 메일 발송 기록 (이메일별 발송 횟수 제한) ─────────
DROP TABLE sms_send_logs;

CREATE TABLE email_send_logs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash  varchar(64) NOT NULL,     -- 소문자 이메일의 SHA-256. 이메일 원문은 저장하지 않는다
    purpose     varchar(20) NOT NULL,     -- SIGNUP / PASSWORD_RESET
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL
);
CREATE INDEX ix_email_send_logs_email_time ON email_send_logs (email_hash, created_at DESC);

-- ───────── 알림 동의: 문자 → 이메일 ─────────
UPDATE user_consents SET consent_type = 'EMAIL_NOTIFY' WHERE consent_type = 'SMS_NOTIFY';
