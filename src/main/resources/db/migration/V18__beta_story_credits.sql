-- 베타 무료 이용권과 초대 코드.
-- 동화 한 편을 AI로 처음 만들 때(POST /confirm) 이용권 1회를 쓴다. 다시 만들기·다시 시도는 같은 동화라 쓰지 않는다.
-- 초대 코드(공용, 선착순 인원)와 사전 연락 이메일로 가입하면 무료 2회, 일반 가입과 기존 회원은 무료 1회.
-- 초대 코드와 사전 연락 이메일은 비밀이라 마이그레이션에 넣지 않고 서버에서 SQL로 넣는다 (docs/deploy/ec2.md).

-- ───────── 초대 코드 (공용 링크 하나를 여러 명이 쓴다) ─────────
CREATE TABLE invite_codes (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               varchar(40) NOT NULL UNIQUE,
    max_uses           integer     NOT NULL CHECK (max_uses >= 0),    -- 선착순 인원
    used_count         integer     NOT NULL DEFAULT 0 CHECK (used_count >= 0),
    closes_at          timestamptz NOT NULL,                          -- 이 시각부터 링크가 동작하지 않는다
    credit_amount      integer     NOT NULL CHECK (credit_amount > 0),
    credit_expires_at  timestamptz,                                   -- 받은 이용권을 이 시각까지 쓸 수 있다. NULL이면 기한 없음
    created_at         timestamptz NOT NULL,
    updated_at         timestamptz NOT NULL
);

-- ───────── 사전 연락 이메일 (이 이메일로 가입하면 초대 코드 없이 무료 이용권) ─────────
CREATE TABLE pre_contacts (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              varchar(255) NOT NULL UNIQUE,                  -- 소문자
    credit_amount      integer      NOT NULL CHECK (credit_amount > 0),
    credit_expires_at  timestamptz,
    granted_user_id    bigint       REFERENCES users (id),            -- 이용권을 준 회원. NULL이면 아직 안 줌
    granted_at         timestamptz,
    created_at         timestamptz  NOT NULL,
    updated_at         timestamptz  NOT NULL
);

-- ───────── 회원: 가입 경로 ─────────
ALTER TABLE users ADD COLUMN signup_source varchar(20) NOT NULL DEFAULT 'GENERAL';   -- GENERAL / INVITE / PRE_CONTACT / DEV

-- ───────── 이용권과 사용 기록 ─────────
CREATE TABLE story_credits (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint      NOT NULL REFERENCES users (id),
    source          varchar(20) NOT NULL,                             -- SIGNUP_FREE / INVITE / PRE_CONTACT (나중에 SUBSCRIPTION)
    amount          integer     NOT NULL CHECK (amount >= 0),
    expires_at      timestamptz,                                      -- NULL이면 기한 없음
    invite_code_id  bigint      REFERENCES invite_codes (id),
    created_at      timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL
);
CREATE INDEX ix_story_credits_user ON story_credits (user_id);

-- 이용권 1회 = 동화 한 편. 동화를 지워도 남는다 (AI는 이미 돌았다)
CREATE TABLE story_credit_uses (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_id   bigint      NOT NULL REFERENCES story_credits (id),
    story_id    bigint      NOT NULL UNIQUE REFERENCES stories (id),
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL
);
CREATE INDEX ix_story_credit_uses_credit ON story_credit_uses (credit_id);

-- 기존 회원은 예전에 만든 동화와 상관없이 새로 무료 1회
INSERT INTO story_credits (user_id, source, amount, expires_at, created_at, updated_at)
SELECT id, 'SIGNUP_FREE', 1, NULL, now(), now() FROM users;
