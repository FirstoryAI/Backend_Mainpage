-- V17: 동화 확정 전 피드백과 함께 읽기 완료 후 피드백 (Backend#76)
-- 선택 답은 enum 코드(name)로 저장한다. 화면 문구는 enum에만 둔다. comment는 비었으면 null
-- 동화마다, 읽기 세션마다 하나만 저장한다(다시 보내도 겹치지 않게 UNIQUE)

CREATE TABLE story_feedbacks (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id              bigint       NOT NULL UNIQUE REFERENCES stories (id),
    version_id            bigint       NOT NULL REFERENCES story_versions (id),   -- 확정한 버전
    situation_reflection  varchar(30)  NOT NULL,
    story_satisfaction    varchar(30)  NOT NULL,
    reading_intent        varchar(30)  NOT NULL,
    comment               varchar(500),
    created_at            timestamptz  NOT NULL,
    updated_at            timestamptz  NOT NULL
);

CREATE TABLE reading_feedbacks (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id                bigint       NOT NULL UNIQUE REFERENCES reading_sessions (id),
    story_id                  bigint       NOT NULL REFERENCES stories (id),
    child_interest            varchar(30)  NOT NULL,
    conversation_flow         varchar(30)  NOT NULL,
    conversation_helpfulness  varchar(30)  NOT NULL,
    comment                   varchar(500),
    created_at                timestamptz  NOT NULL,
    updated_at                timestamptz  NOT NULL
);
CREATE INDEX ix_reading_feedbacks_story ON reading_feedbacks (story_id);
