-- FIRSTORY 초기 스키마 (ERD v0.7 기준). 이 파일이 스키마의 기준이다.
-- 시간은 모두 timestamptz(UTC). 소프트 삭제 테이블은 deleted_at을 둔다.

-- ───────── 회원 ─────────
CREATE TABLE users (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               varchar(255) NOT NULL,
    password_hash       varchar(100) NOT NULL,
    phone_enc           varchar(255) NOT NULL,
    phone_hash          varchar(64)  NOT NULL,
    phone_verified_at   timestamptz  NOT NULL,
    onboarding_seen_at  timestamptz,
    deleted_at          timestamptz,
    created_at          timestamptz  NOT NULL,
    updated_at          timestamptz  NOT NULL
);
-- 탈퇴한 회원은 중복 검사에서 제외 (부분 UNIQUE)
CREATE UNIQUE INDEX ux_users_email_active      ON users (email)      WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX ux_users_phone_hash_active ON users (phone_hash) WHERE deleted_at IS NULL;

CREATE TABLE user_consents (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint      NOT NULL REFERENCES users (id),
    consent_type   varchar(30) NOT NULL,   -- GUARDIAN / TERMS / PRIVACY / SMS_NOTIFY
    agreed         boolean     NOT NULL,
    terms_version  varchar(20) NOT NULL,
    agreed_at      timestamptz,
    withdrawn_at   timestamptz,
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL
);
CREATE INDEX ix_user_consents_user ON user_consents (user_id, consent_type);

-- ───────── 아이 ─────────
CREATE TABLE children (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint      NOT NULL REFERENCES users (id),
    display_name  varchar(30) NOT NULL,              -- 기본 "아이 A". AI로 보내지 않음
    birth_ym      varchar(7)  NOT NULL,              -- "2021-03"
    gender        varchar(20) NOT NULL,              -- FEMALE / MALE / UNDISCLOSED
    interests     jsonb       NOT NULL DEFAULT '[]', -- 최대 5개
    deleted_at    timestamptz,
    created_at    timestamptz NOT NULL,
    updated_at    timestamptz NOT NULL
);
CREATE INDEX ix_children_user ON children (user_id) WHERE deleted_at IS NULL;

CREATE TABLE child_traits (
    child_id    bigint      NOT NULL REFERENCES children (id) ON DELETE CASCADE,
    trait_code  varchar(30) NOT NULL,                -- Trait enum
    PRIMARY KEY (child_id, trait_code)
);

-- ───────── 동화 ─────────
CREATE TABLE stories (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  bigint       NOT NULL REFERENCES users (id),
    child_id                 bigint       REFERENCES children (id),   -- 저장 안 함이면 null
    thread_id                varchar(64)  NOT NULL UNIQUE,
    status                   varchar(30)  NOT NULL,
    current_version_id       bigint,                                  -- FK는 아래에서 추가
    title                    varchar(100),
    regenerate_count         integer      NOT NULL DEFAULT 0,
    confirmed_at             timestamptz,
    first_read_completed_at  timestamptz,
    deleted_at               timestamptz,
    created_at               timestamptz  NOT NULL,
    updated_at               timestamptz  NOT NULL
);
CREATE INDEX ix_stories_user_created ON stories (user_id, created_at DESC) WHERE deleted_at IS NULL;

CREATE TABLE story_inputs (
    story_id              bigint PRIMARY KEY REFERENCES stories (id),
    situation_timing      varchar(20),
    situation_category    varchar(50),
    description           text,
    moment_reaction       text,
    emotion               varchar(30),
    parent_message        text,
    message_direction     varchar(50),
    tone                  varchar(20),
    child_snapshot        jsonb,
    interview_summary     text,
    interview_end_reason  varchar(20),
    created_at            timestamptz NOT NULL,
    updated_at            timestamptz NOT NULL
);

CREATE TABLE interview_turns (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id        bigint      NOT NULL REFERENCES stories (id),
    turn_no         integer     NOT NULL CHECK (turn_no BETWEEN 1 AND 5),
    question        text        NOT NULL,
    answer          text,
    context_update  jsonb,
    answered_at     timestamptz,
    created_at      timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL,
    UNIQUE (story_id, turn_no)
);

CREATE TABLE safety_flags (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id           bigint      NOT NULL REFERENCES stories (id),
    source             varchar(20) NOT NULL,     -- FORM / INTERVIEW
    interview_turn_id  bigint      REFERENCES interview_turns (id),
    category           varchar(50) NOT NULL,     -- AI가 분류
    ai_reason          text,
    occurrence_no      integer     NOT NULL,     -- 이 동화에서 몇 번째
    user_response      varchar(20),              -- HELP_OPENED / DISMISSED
    detected_at        timestamptz NOT NULL,
    created_at         timestamptz NOT NULL,
    updated_at         timestamptz NOT NULL,
    UNIQUE (story_id, occurrence_no)
);

-- ───────── 생성 ─────────
CREATE TABLE generation_runs (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id            bigint      NOT NULL REFERENCES stories (id),
    run_no              integer     NOT NULL,
    trigger_type        varchar(20) NOT NULL,    -- INITIAL / REGENERATE / RETRY
    scope               varchar(30) NOT NULL,    -- ALL / CHARACTER_STORY / TEXT / IMAGES
    base_version_id     bigint,                  -- FK는 아래에서 추가
    feedback            text,
    status              varchar(20) NOT NULL,    -- RUNNING / SUCCEEDED / FAILED
    current_node        varchar(50),
    langsmith_trace_id  varchar(64),
    input_tokens        integer     NOT NULL DEFAULT 0,
    output_tokens       integer     NOT NULL DEFAULT 0,
    image_count         integer     NOT NULL DEFAULT 0,
    error_code          varchar(100),
    started_at          timestamptz NOT NULL,
    finished_at         timestamptz,
    created_at          timestamptz NOT NULL,
    updated_at          timestamptz NOT NULL,
    UNIQUE (story_id, run_no)
);

CREATE TABLE story_versions (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id             bigint       NOT NULL REFERENCES stories (id),
    run_id               bigint       NOT NULL UNIQUE REFERENCES generation_runs (id),
    version_no           integer      NOT NULL,
    parent_version_id    bigint       REFERENCES story_versions (id),
    title                varchar(100) NOT NULL,
    checkpoint_id        varchar(100),
    design               jsonb,
    character_sheet_key  varchar(255),
    created_at           timestamptz  NOT NULL,
    updated_at           timestamptz  NOT NULL,
    UNIQUE (story_id, version_no)
);

ALTER TABLE stories
    ADD CONSTRAINT fk_stories_current_version FOREIGN KEY (current_version_id) REFERENCES story_versions (id);
ALTER TABLE generation_runs
    ADD CONSTRAINT fk_runs_base_version FOREIGN KEY (base_version_id) REFERENCES story_versions (id);

CREATE TABLE story_pages (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id    bigint       NOT NULL REFERENCES story_versions (id),
    page_no       integer      NOT NULL CHECK (page_no BETWEEN 1 AND 10),
    text          text         NOT NULL,
    image_prompt  text,
    image_key     varchar(255),
    image_status  varchar(20)  NOT NULL,     -- PENDING / DONE / FAILED
    created_at    timestamptz  NOT NULL,
    updated_at    timestamptz  NOT NULL,
    UNIQUE (version_id, page_no)
);

-- ───────── 대화 가이드 ─────────
CREATE TABLE reading_guides (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id       bigint      NOT NULL UNIQUE REFERENCES story_versions (id),
    before_intent    text,
    before_tips      jsonb       NOT NULL DEFAULT '[]',
    bridge_question  text,
    if_undecided     text,
    created_at       timestamptz NOT NULL,
    updated_at       timestamptz NOT NULL
);

CREATE TABLE guide_prompts (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guide_id     bigint      NOT NULL REFERENCES reading_guides (id),
    seq          integer     NOT NULL,
    after_page   integer     NOT NULL CHECK (after_page BETWEEN 1 AND 10),
    question     text        NOT NULL,   -- 04-guide.json의 prompts[].text
    purpose      varchar(50),
    parent_hint  text,
    created_at   timestamptz NOT NULL,
    updated_at   timestamptz NOT NULL,
    UNIQUE (guide_id, seq)
);

-- ───────── 함께 읽기 ─────────
CREATE TABLE reading_sessions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_id      bigint      NOT NULL REFERENCES stories (id),
    version_id    bigint      NOT NULL REFERENCES story_versions (id),
    last_page     integer     NOT NULL DEFAULT 0,
    started_at    timestamptz NOT NULL,
    completed_at  timestamptz,
    created_at    timestamptz NOT NULL,
    updated_at    timestamptz NOT NULL
);
CREATE INDEX ix_reading_sessions_story ON reading_sessions (story_id, started_at DESC);

CREATE TABLE dialogue_actions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  bigint      NOT NULL REFERENCES reading_sessions (id),
    prompt_id   bigint      NOT NULL REFERENCES guide_prompts (id),
    action      varchar(20) NOT NULL,     -- TALKED / SKIPPED
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,
    UNIQUE (session_id, prompt_id)
);

-- ───────── 알림 ─────────
CREATE TABLE notifications (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint       NOT NULL REFERENCES users (id),
    story_id           bigint       NOT NULL REFERENCES stories (id),
    generation_run_id  bigint       NOT NULL REFERENCES generation_runs (id),
    type               varchar(30)  NOT NULL,   -- STORY_STARTED / STORY_COMPLETED / STORY_FAILED
    channel            varchar(20)  NOT NULL,   -- SMS (나중에 WEB_PUSH)
    template_code      varchar(50)  NOT NULL,
    status             varchar(20)  NOT NULL,   -- PENDING / SENT / FAILED
    provider_msg_id    varchar(100),
    fail_reason        varchar(255),
    sent_at            timestamptz,
    created_at         timestamptz  NOT NULL,
    updated_at         timestamptz  NOT NULL,
    UNIQUE (generation_run_id, type)            -- 같은 실행에 같은 알림 두 번 금지
);
