-- V2: 로그인 세션, 로그인 상태 유지(remember-me), 로그인 잠금, 문자 발송 제한
-- 세션 저장소는 PostgreSQL(Spring Session JDBC). 스키마는 Flyway가 만들고 Spring Session의 자동 생성은 끈다.

-- ───────── Spring Session JDBC (spring-session-jdbc 공식 PostgreSQL 스키마) ─────────
-- PRINCIPAL_NAME은 로그인 이메일(최대 255자)을 담기 위해 100 → 255로 늘렸다.
CREATE TABLE spring_session (
    primary_id             char(36)     NOT NULL,
    session_id             char(36)     NOT NULL,
    creation_time          bigint       NOT NULL,
    last_access_time       bigint       NOT NULL,
    max_inactive_interval  int          NOT NULL,
    expiry_time            bigint       NOT NULL,
    principal_name         varchar(255),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);
CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id  char(36)     NOT NULL,
    attribute_name      varchar(200) NOT NULL,
    attribute_bytes     bytea        NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);

-- ───────── Remember-me (Spring Security JdbcTokenRepositoryImpl 형식) ─────────
-- username에는 로그인 이메일이 들어간다. 기본 스키마의 64자는 이메일에 부족해서 255로 늘렸다.
CREATE TABLE persistent_logins (
    username   varchar(255) NOT NULL,
    series     varchar(64)  PRIMARY KEY,
    token      varchar(64)  NOT NULL,
    last_used  timestamp    NOT NULL
);
CREATE INDEX ix_persistent_logins_username ON persistent_logins (username);

-- ───────── 로그인 실패 잠금 ─────────
ALTER TABLE users
    ADD COLUMN failed_login_count integer NOT NULL DEFAULT 0,
    ADD COLUMN locked_until       timestamptz;

-- ───────── 문자 발송 기록 (번호별 발송 횟수 제한, 비용 추적) ─────────
CREATE TABLE sms_send_logs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_hash  varchar(64) NOT NULL,     -- PhoneCrypto.hash. 평문 번호는 저장하지 않는다
    purpose     varchar(20) NOT NULL,     -- SIGNUP / CHANGE_PHONE
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL
);
CREATE INDEX ix_sms_send_logs_phone_time ON sms_send_logs (phone_hash, created_at DESC);
